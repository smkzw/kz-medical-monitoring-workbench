"""mm_r4 -- isolated R4 medical monitoring common contract (synthetic only).

The R4 package implements the frozen common coverage contract
(``FROZEN_R4_CONTRACT_V1``), the AE/MH longitudinal slice, and the CM
medication-review slice on top of
the frozen R1/R2/R3 public surfaces.  It imports frozen public APIs read-only
(R1 ``CoverageUnitStatus`` for L0 values, R2 ``RiskLifecycleState`` for L3
authority, R2 ``make_risk_identity`` / ``RiskLifecycle`` / ``AcceptanceService``,
R3 ``normalize_partial_date``) and does not copy or fork lifecycle or
normalization authority.

Public surface:

* Layer-namespace codes and coverage ledger (:mod:`mm_r4.contracts`,
  :mod:`mm_r4.coverage`)
* D01 AE/MH semantic-role slice (:mod:`mm_r4.aemh`)
* D02 CM medication-review slice and journey projection (:mod:`mm_r4.cm`,
  :mod:`mm_r4.cm_projection`)
* D03 IP exposure/adherence/accountability slice and journey projection
  (:mod:`mm_r4.ip`, :mod:`mm_r4.ip_projection`)
* D04 protocol-compliance slice: domain model, journey projection and
  83-case challenge matrix (:mod:`mm_r4.protocol`,
  :mod:`mm_r4.protocol_projection`, :mod:`mm_r4.protocol_fixtures`)
* D05 visit/assessment/sample timing slice: domain model, evaluator,
  renderer-neutral journey projection and 116-case challenge matrix
  (:mod:`mm_r4.visit_schedule`, :mod:`mm_r4.visit_schedule_evaluator`,
  :mod:`mm_r4.visit_schedule_projection`,
  :mod:`mm_r4.visit_schedule_fixtures`)
* D06 efficacy endpoint/scale/individual-trend slice: domain model,
  deterministic evaluator with the five frozen entrypoints, renderer-
  neutral journey projection and the 219-case frozen challenge matrix
  with DSL/oracle verification (:mod:`mm_r4.efficacy`,
  :mod:`mm_r4.efficacy_evaluator`, :mod:`mm_r4.efficacy_projection`,
  :mod:`mm_r4.efficacy_fixtures`)
* D07 clinical safety / laboratory / examination slice: closed typed
  runtime with the frozen pre-evaluator integrity pipeline, deterministic
  medical evaluation (range/grade/baseline/trend/CS-NCS/follow-up/organ-
  pattern/examination/owner/priority/lifecycle), three-part Chinese Query
  draft with D04 PD-wording permission, and the shared visit-axis Journey
  projection with audience validation (:mod:`mm_r4.d07_safety`,
  :mod:`mm_r4.d07_safety_evaluator`, :mod:`mm_r4.d07_journey`,
  :mod:`mm_r4.d07_query`)
* Query / journey projection data (:mod:`mm_r4.projection`)
* R2 lifecycle adapter (:mod:`mm_r4.lifecycle`)
* Synthetic challenge fixtures (:mod:`mm_r4.fixtures`,
  :mod:`mm_r4.cm_fixtures`, :mod:`mm_r4.ip_fixtures`)
"""

